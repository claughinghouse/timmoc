import { it } from "@effect/vitest";
import { env } from "cloudflare:workers";
import { runInDurableObject } from "cloudflare:test";
import { expect } from "vite-plus/test";
import { RuntimeContext } from "alchemy/RuntimeContext";
import * as Effect from "effect/Effect";
import * as HttpServerRequest from "effect/http/HttpServerRequest";
import * as HttpServerResponse from "effect/http/HttpServerResponse";
import { app } from "./app.ts";
import quotes from "./quotes.ts";

it.effect("parameter-free GET routes share IP limits but catalog messages remain available", () =>
  Effect.gen(function* () {
    const names: string[] = [];
    const histories = {
      getByName: (name: string) => {
        names.push(name);
        const stub = env.HISTORY.getByName(`http-${name}`);
        return {
          next: () => Effect.promise(async () => await stub.next()),
          generate: () => Effect.promise(async () => await stub.generate()),
        };
      },
    };
    for (let i = 0; i < 7; i++) {
      const path = i === 6 ? "/unique" : "/generate";
      const ip = i % 2 === 0 ? "2001:0db8:0:0:0:0:0:1" : "2001:db8::1";
      const result = yield* app(histories).pipe(
        Effect.provideService(
          HttpServerRequest.HttpServerRequest,
          HttpServerRequest.fromWeb(
            new Request(`https://timmoc.dev${path}`, { headers: { "cf-connecting-ip": ip } }),
          ),
        ),
        Effect.provide(RuntimeContext.phantom),
      );
      expect(result.status).toBe(i === 5 ? 429 : 200);
      expect(result.headers["cache-control"]).toBe("private, no-store");
      const body = yield* Effect.promise(() => HttpServerResponse.toWeb(result).text());
      if (i < 5) expect(body).toBe("Generated by the test model");
      if (i === 5) expect(result.headers["retry-after"]).toBe("60");
      if (i === 6) expect(quotes.map((quote) => quote.trim())).toContain(body);
    }
    expect(new Set(names).size).toBe(1);
    expect(names[0]).toMatch(/^[0-9a-f]{64}$/);
    const name = names[0];
    if (name === undefined) throw new Error("Expected IP lookup");
    yield* Effect.promise(() =>
      runInDurableObject(env.HISTORY.getByName(`http-${name}`), async (_, state) => {
        await state.storage.put("history", {
          expiresAt: Date.now() + 60_000,
          messages: quotes.map((quote) => quote.trim()),
        });
      }),
    );
    const limited = yield* app(histories).pipe(
      Effect.provideService(
        HttpServerRequest.HttpServerRequest,
        HttpServerRequest.fromWeb(
          new Request("https://timmoc.dev/unique", {
            headers: { "cf-connecting-ip": "2001:db8::1" },
          }),
        ),
      ),
      Effect.provide(RuntimeContext.phantom),
    );
    expect(limited.status).toBe(429);
    expect(limited.headers["retry-after"]).toBe("60");
  }),
);

it.effect("rejects missing/invalid IPs and non-GET methods before touching state", () =>
  Effect.gen(function* () {
    for (const path of ["/unique", "/generate"]) {
      for (const [method, ip, status] of [
        ["GET", "", 400],
        ["GET", "bad-ip", 400],
        ["POST", "192.0.2.4", 405],
      ] as const) {
        const result = yield* app({
          getByName: () => {
            throw new Error("Unexpected IP tracking");
          },
        }).pipe(
          Effect.provideService(
            HttpServerRequest.HttpServerRequest,
            HttpServerRequest.fromWeb(
              new Request(`https://timmoc.dev${path}`, {
                method,
                headers: { "cf-connecting-ip": ip },
              }),
            ),
          ),
          Effect.provide(RuntimeContext.phantom),
        );
        expect(result.status).toBe(status);
        if (status === 405) expect(result.headers.allow).toBe("GET");
      }
    }
  }),
);

it.effect("keeps / stateless and returns 503 when direct generation is unavailable", () =>
  Effect.gen(function* () {
    for (const [path, status] of [
      ["/", 200],
      ["/generate", 503],
      ["/missing", 404],
    ] as const) {
      const result = yield* app({
        getByName: () => {
          expect(path).toBe("/generate");
          return {
            next: () => Effect.die("Unexpected history"),
            generate: () => Effect.succeed({ status: "unavailable" } as const),
          };
        },
      }).pipe(
        Effect.provideService(
          HttpServerRequest.HttpServerRequest,
          HttpServerRequest.fromWeb(
            new Request(`https://timmoc.dev${path}`, {
              headers: { "cf-connecting-ip": "192.0.2.8" },
            }),
          ),
        ),
        Effect.provide(RuntimeContext.phantom),
      );
      expect(result.status).toBe(status);
      if (path === "/")
        expect(quotes).toContain(
          yield* Effect.promise(() => HttpServerResponse.toWeb(result).text()),
        );
    }
  }),
);
