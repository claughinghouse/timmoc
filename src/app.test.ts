import { it } from "@effect/vitest";
import { env } from "cloudflare:workers";
import { runInDurableObject } from "cloudflare:test";
import { expect } from "vite-plus/test";
import { RuntimeContext } from "alchemy/RuntimeContext";
import * as Effect from "effect/Effect";
import * as HttpServerRequest from "effect/http/HttpServerRequest";
import * as HttpServerResponse from "effect/http/HttpServerResponse";
import { app } from "./app.ts";
import quotes from "./quotes.ts";

it.effect("keeps / stateless and rejects removed/unknown routes without touching state", () =>
  Effect.gen(function* () {
    for (const [path, status] of [
      ["/", 200],
      ["/generate", 404],
      ["/missing", 404],
    ] as const) {
      for (const method of ["GET", "POST"]) {
        const response = yield* app({
          getByName: () => {
            throw new Error("Stateless or removed route must not access state or AI");
          },
        }).pipe(
          Effect.provideService(
            HttpServerRequest.HttpServerRequest,
            HttpServerRequest.fromWeb(new Request(`https://timmoc.dev${path}`, { method })),
          ),
          Effect.provide(RuntimeContext.phantom),
        );
        expect(response.status).toBe(status);
        if (path === "/") {
          expect(quotes).toContain(
            yield* Effect.promise(() => HttpServerResponse.toWeb(response).text()),
          );
        }
      }
    }
  }),
);

it.effect("serves robots.txt without accessing IP history or AI", () =>
  Effect.gen(function* () {
    for (const [method, status] of [
      ["GET", 200],
      ["HEAD", 200],
      ["POST", 405],
    ] as const) {
      const response = yield* app({
        getByName: () => {
          throw new Error("robots.txt must not access state or AI");
        },
      }).pipe(
        Effect.provideService(
          HttpServerRequest.HttpServerRequest,
          HttpServerRequest.fromWeb(new Request("https://timmoc.dev/robots.txt", { method })),
        ),
        Effect.provide(RuntimeContext.phantom),
      );
      expect(response.status).toBe(status);
      const body = yield* Effect.promise(() => HttpServerResponse.toWeb(response).text());
      if (status === 200) {
        expect(response.headers["content-type"]).toBe("text/plain; charset=utf-8");
        expect(response.headers["cache-control"]).toBe("public, max-age=86400");
        expect(body).toBe(method === "HEAD" ? "" : "User-agent: *\nDisallow: /\n");
      } else {
        expect(response.headers.allow).toBe("GET, HEAD");
      }
    }
  }),
);

it.effect(
  "canonicalizes IPs, serves catalog first, then rate-limits generation after exhaustion",
  () =>
    Effect.gen(function* () {
      const names: string[] = [];
      const histories = {
        getByName: (name: string) => {
          names.push(name);
          const stub = env.HISTORY.getByName(`http-${name}`);
          return { next: () => Effect.promise(async () => await stub.next()) };
        },
      };
      for (let i = 0; i < 8; i++) {
        const ip = i % 2 === 0 ? "2001:0db8:0:0:0:0:0:1" : "2001:db8::1";
        const result = yield* app(histories).pipe(
          Effect.provideService(
            HttpServerRequest.HttpServerRequest,
            HttpServerRequest.fromWeb(
              new Request("https://timmoc.dev/unique", { headers: { "cf-connecting-ip": ip } }),
            ),
          ),
          Effect.provide(RuntimeContext.phantom),
        );
        expect(result.status).toBe(i === 7 ? 429 : 200);
        expect(result.headers["cache-control"]).toBe("private, no-store");
        const body = yield* Effect.promise(() => HttpServerResponse.toWeb(result).text());
        if (i < 2) expect(quotes.map((quote) => quote.trim())).toContain(body);
        if (i >= 2 && i < 7) expect(body).toBe("Generated by the test model");
        if (i === 7) expect(result.headers["retry-after"]).toBe("60");
        if (i === 1) {
          const name = names[0];
          if (name === undefined) throw new Error("Expected IP lookup");
          yield* Effect.promise(() =>
            runInDurableObject(env.HISTORY.getByName(`http-${name}`), async (_, state) => {
              await state.storage.put("history", {
                expiresAt: Date.now() + 60_000,
                messages: quotes.map((quote) => quote.trim()),
              });
            }),
          );
        }
      }
      expect(new Set(names).size).toBe(1);
      expect(names[0]).toMatch(/^[0-9a-f]{64}$/);
    }),
);

it.effect("returns 503 with Retry-After after AI failures instead of a catalog message", () =>
  Effect.gen(function* () {
    const stub = env.HISTORY.getByName("http-unavailable");
    const history = {
      expiresAt: Date.now() + 60_000,
      messages: quotes.map((quote) => quote.trim()),
    };
    yield* Effect.promise(() =>
      runInDurableObject(stub, async (instance, state) => {
        instance.failGeneration = true;
        await state.storage.put("history", history);
      }),
    );
    const result = yield* app({
      getByName: () => ({ next: () => Effect.promise(async () => await stub.next()) }),
    }).pipe(
      Effect.provideService(
        HttpServerRequest.HttpServerRequest,
        HttpServerRequest.fromWeb(
          new Request("https://timmoc.dev/unique", {
            headers: { "cf-connecting-ip": "192.0.2.10" },
          }),
        ),
      ),
      Effect.provide(RuntimeContext.phantom),
    );
    expect(result.status).toBe(503);
    expect(result.headers["retry-after"]).toBe("30");
    expect(result.headers["cache-control"]).toBe("private, no-store");
    expect(yield* Effect.promise(() => HttpServerResponse.toWeb(result).text())).toBe(
      "Generation unavailable; try again later",
    );
    const stored = yield* Effect.promise(() =>
      runInDurableObject(stub, (_, state) => state.storage.get("history")),
    );
    expect(stored).toEqual(history);
  }),
);

it.effect("rejects missing/invalid IPs and non-GET methods before touching state", () =>
  Effect.gen(function* () {
    for (const [method, ip, status] of [
      ["GET", "", 400],
      ["GET", "bad-ip", 400],
      ["POST", "192.0.2.4", 405],
    ] as const) {
      const result = yield* app({
        getByName: () => {
          throw new Error("Unexpected IP tracking");
        },
      }).pipe(
        Effect.provideService(
          HttpServerRequest.HttpServerRequest,
          HttpServerRequest.fromWeb(
            new Request("https://timmoc.dev/unique", {
              method,
              headers: { "cf-connecting-ip": ip },
            }),
          ),
        ),
        Effect.provide(RuntimeContext.phantom),
      );
      expect(result.status).toBe(status);
      if (status === 405) expect(result.headers.allow).toBe("GET");
    }
  }),
);
