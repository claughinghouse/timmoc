import { env } from "cloudflare:workers";
import { evictDurableObject, runDurableObjectAlarm, runInDurableObject } from "cloudflare:test";
import { expect, it } from "vite-plus/test";
import quotes from "./quotes.ts";

const catalog = [...new Set(quotes.map((quote) => quote.trim()))];

it("records each catalog message before generating, persists across eviction, and isolates callers", async () => {
  const stub = env.HISTORY.getByName("catalog");
  const first = await stub.next();
  await evictDurableObject(stub);
  const rest = await Promise.all(Array.from({ length: catalog.length - 1 }, () => stub.next()));
  expect(new Set([first, ...rest])).toEqual(
    new Set(catalog.map((message) => ({ status: "ok", message }))),
  );
  const persisted = await runInDurableObject(stub, async (_, state) =>
    state.storage.get("history"),
  );
  expect(persisted).toMatchObject({ messages: expect.arrayContaining(catalog) });
  await runInDurableObject(stub, (instance) => {
    expect(instance.examples).toEqual([]);
  });
  expect(await stub.next()).toEqual({ status: "ok", message: "Generated by the test model" });
  expect(await stub.next()).toEqual({ status: "ok", message: "Generated by the test model" });
  await runInDurableObject(stub, (instance) => {
    expect(instance.examples).toEqual(
      expect.arrayContaining([...catalog, "Generated by the test model"]),
    );
  });
  expect(catalog.map((message) => ({ status: "ok", message }))).toContainEqual(
    await env.HISTORY.getByName("different-caller").next(),
  );
});

it("sets a fixed one-year alarm, ignores an early alarm, and deletes all state at expiry", async () => {
  const stub = env.HISTORY.getByName("expiry");
  const before = Date.now();
  await stub.next();
  const alarm = await runInDurableObject(stub, (_, state) => state.storage.getAlarm());
  expect(alarm).toBeGreaterThanOrEqual(before + 365 * 24 * 60 * 60 * 1000);
  expect(alarm).toBeLessThanOrEqual(Date.now() + 365 * 24 * 60 * 60 * 1000);
  await stub.next();
  expect(await runInDurableObject(stub, (_, state) => state.storage.getAlarm())).toBe(alarm);
  await runDurableObjectAlarm(stub);
  expect(await runInDurableObject(stub, (_, state) => state.storage.get("history"))).toBeDefined();
  await runInDurableObject(stub, async (_, state) => {
    await state.storage.put("history", { expiresAt: 0, messages: catalog });
    await state.storage.setAlarm(Date.now() + 60_000);
  });
  expect(await runDurableObjectAlarm(stub)).toBe(true);
  expect(await runInDurableObject(stub, (_, state) => state.storage.list())).toEqual(new Map());
  expect(await runInDurableObject(stub, (_, state) => state.storage.getAlarm())).toBeNull();
  expect(catalog.map((message) => ({ status: "ok", message }))).toContainEqual(await stub.next());
});

it("reports unavailable after bounded retries without changing history, and persists every attempt", async () => {
  const stub = env.HISTORY.getByName("failure");
  const history = { expiresAt: Date.now() + 60_000, messages: catalog };
  await runInDurableObject(stub, async (instance, state) => {
    instance.failGeneration = true;
    await state.storage.put("history", history);
  });
  expect(await stub.next()).toEqual({ status: "unavailable" });
  expect(await runInDurableObject(stub, (_, state) => state.storage.get("history"))).toEqual(
    history,
  );
  expect(await runInDurableObject(stub, (_, state) => state.storage.get("limits"))).toHaveLength(3);
  // A second request can spend only the remaining two slots before returning 429.
  expect((await stub.next()).status).toBe("limited");
  expect(await runInDurableObject(stub, (_, state) => state.storage.get("limits"))).toHaveLength(5);
  await evictDurableObject(stub);
  expect((await stub.next()).status).toBe("limited");
});

it("retries provider errors and invalid responses, saving only the successful message", async () => {
  for (const reason of ["inference-failed", "invalid-response", "invalid-message"] as const) {
    const stub = env.HISTORY.getByName(`retry-${reason}`);
    const history = { expiresAt: Date.now() + 60_000, messages: catalog };
    await runInDurableObject(stub, async (instance, state) => {
      instance.failuresRemaining = 2;
      instance.generationFailureReason = reason;
      await state.storage.put("history", history);
    });
    expect(await stub.next()).toEqual({ status: "ok", message: "Generated by the test model" });
    await runInDurableObject(stub, async (instance, state) => {
      expect(instance.generationAttempts).toBe(3);
      expect(await state.storage.get("limits")).toHaveLength(3);
      expect(await state.storage.get("history")).toEqual({
        ...history,
        messages: [...catalog, "Generated by the test model"],
      });
    });
  }
});

it("does not retry invalid examples or modify their history", async () => {
  const stub = env.HISTORY.getByName("invalid-examples");
  const history = { expiresAt: Date.now() + 60_000, messages: catalog };
  await runInDurableObject(stub, async (instance, state) => {
    instance.failGeneration = true;
    instance.generationFailureReason = "invalid-examples";
    await state.storage.put("history", history);
  });
  expect(await stub.next()).toEqual({ status: "unavailable" });
  await runInDurableObject(stub, async (instance, state) => {
    expect(instance.generationAttempts).toBe(1);
    expect(await state.storage.get("history")).toEqual(history);
  });
});

it("bounds a stuck inference by one 15-second deadline without recording a message", async () => {
  const stub = env.HISTORY.getByName("retry-timeout");
  const history = { expiresAt: Date.now() + 60_000, messages: catalog };
  await runInDurableObject(stub, async (instance, state) => {
    instance.neverGenerate = true;
    await state.storage.put("history", history);
  });
  expect(await stub.next()).toEqual({ status: "unavailable" });
  await runInDurableObject(stub, async (instance, state) => {
    expect(instance.generationAttempts).toBe(1);
    expect(await state.storage.get("history")).toEqual(history);
    expect(await state.storage.get("limits")).toHaveLength(1);
  });
}, 20_000);

it("persists a strict exhaustion-only AI allowance across eviction without limiting catalog messages", async () => {
  const stub = env.HISTORY.getByName("limits");
  const now = await runInDurableObject(stub, (instance) => instance.now);
  await runInDurableObject(stub, async (_, state) => {
    await state.storage.put("history", {
      expiresAt: now + 365 * 24 * 60 * 60 * 1000,
      messages: catalog,
    });
  });
  const results = await Promise.all(Array.from({ length: 9 }, () => stub.next()));
  expect(results.filter((result) => result.status === "ok")).toHaveLength(5);
  expect(results.filter((result) => result.status === "limited")).toEqual(
    Array.from({ length: 4 }, () => ({ status: "limited", retryAfter: 60 })),
  );
  await runInDurableObject(stub, (instance) => expect(instance.examples).toContain(catalog[0]));
  await evictDurableObject(stub);
  await runInDurableObject(stub, (instance) => {
    instance.now = now;
  });
  // An unused catalog message remains available even with all five AI slots used.
  await runInDurableObject(stub, async (_, state) => {
    await state.storage.put("history", {
      expiresAt: now + 365 * 24 * 60 * 60 * 1000,
      messages: catalog.slice(1),
    });
  });
  expect(await stub.next()).toEqual({ status: "ok", message: catalog[0] });
  expect(await stub.next()).toEqual({ status: "limited", retryAfter: 60 });
  const separate = env.HISTORY.getByName("separate-limit");
  await runInDurableObject(separate, async (_, state) => {
    await state.storage.put("history", { expiresAt: now + 60_000, messages: catalog });
  });
  expect(await separate.next()).toEqual({
    status: "ok",
    message: "Generated by the test model",
  });
  await runInDurableObject(stub, (instance) => {
    instance.now = now + 59_999;
  });
  expect(await stub.next()).toEqual({ status: "limited", retryAfter: 1 });
  await runInDurableObject(stub, (instance) => {
    instance.now = now + 60_000;
  });
  expect(await stub.next()).toEqual({ status: "ok", message: "Generated by the test model" });
});

it("expires rolling attempts individually and cleans counters without removing active history", async () => {
  const stub = env.HISTORY.getByName("rolling");
  const now = await runInDurableObject(stub, (instance) => instance.now);
  await runInDurableObject(stub, async (_, state) => {
    await state.storage.put("history", {
      expiresAt: now + 365 * 24 * 60 * 60 * 1000,
      messages: catalog,
    });
  });
  await stub.next();
  await runInDurableObject(stub, (instance) => {
    instance.now = now + 10_000;
  });
  await Promise.all(Array.from({ length: 4 }, () => stub.next()));
  await runInDurableObject(stub, (instance) => {
    instance.now = now + 60_000;
  });
  expect((await stub.next()).status).toBe("ok");
  expect(await stub.next()).toEqual({ status: "limited", retryAfter: 10 });
  await runInDurableObject(stub, (instance) => {
    instance.now = now + 120_000;
  });
  await runDurableObjectAlarm(stub);
  expect(await runInDurableObject(stub, (_, state) => state.storage.get("limits"))).toBeUndefined();
  expect(await runInDurableObject(stub, (_, state) => state.storage.get("history"))).toBeDefined();
  // Yearly cleanup must not reset AI attempts that are still in their minute window.
  await Promise.all(Array.from({ length: 5 }, () => stub.next()));
  await runInDurableObject(stub, async (_, state) => {
    await state.storage.put("history", { expiresAt: 0, messages: catalog });
  });
  await runDurableObjectAlarm(stub);
  const retainedLimits = await runInDurableObject(stub, (_, state) => state.storage.get("limits"));
  expect(retainedLimits).toHaveLength(5);
  expect(
    await runInDurableObject(stub, (_, state) => state.storage.get("history")),
  ).toBeUndefined();
  await runInDurableObject(stub, (instance) => {
    instance.now = now + 180_000;
  });
  await runDurableObjectAlarm(stub);
  expect(await runInDurableObject(stub, (_, state) => state.storage.list())).toEqual(new Map());
  expect(await runInDurableObject(stub, (_, state) => state.storage.getAlarm())).toBeNull();
});
