import { DurableObject } from "cloudflare:workers";
import { fromDurableObjectStorage } from "@alchemy.run/cloudflare/Workers/DurableObjectStorage";
import { RuntimeContext } from "alchemy/RuntimeContext";
import * as Clock from "effect/Clock";
import * as Effect from "effect/Effect";
import { CommitGenerator, GenerationUnavailable } from "./commit-generator.ts";
import { uniqueCommits } from "./unique-commits.ts";

declare global {
  namespace Cloudflare {
    interface Env {
      HISTORY: DurableObjectNamespace<HistoryFixture>;
    }
  }
}

/** Local workerd host for production history handlers; only inference is substituted. */
export class HistoryFixture extends DurableObject {
  private readonly handlers;
  failGeneration = false;
  examples: readonly string[] = [];
  now = Date.now();
  private readonly clock: Clock.Clock = {
    currentTimeMillisUnsafe: () => this.now,
    currentTimeMillis: Effect.sync(() => this.now),
    currentTimeNanosUnsafe: () => BigInt(this.now) * 1_000_000n,
    currentTimeNanos: Effect.sync(() => BigInt(this.now) * 1_000_000n),
    monotonicTimeNanosUnsafe: () => BigInt(this.now) * 1_000_000n,
    monotonicTimeNanos: Effect.sync(() => BigInt(this.now) * 1_000_000n),
    sleep: () => Effect.void,
  };

  constructor(ctx: globalThis.DurableObjectState, env: Cloudflare.Env) {
    super(ctx, env);
    this.handlers = ctx.blockConcurrencyWhile(() =>
      Effect.runPromise(
        uniqueCommits(fromDurableObjectStorage(ctx.storage)).pipe(
          Effect.flatten,
          Effect.provideService(CommitGenerator, {
            generate: (examples) =>
              Effect.suspend(() => {
                this.examples = examples;
                return this.failGeneration
                  ? Effect.fail(new GenerationUnavailable())
                  : Effect.succeed("Generated by the test model");
              }),
          }),
          Effect.provide(RuntimeContext.phantom),
        ),
      ),
    );
  }

  /** Exercise the same method used by the /unique route. */
  async next() {
    const handlers = await this.handlers;
    return Effect.runPromise(
      handlers
        .next()
        .pipe(
          Effect.provide(RuntimeContext.phantom),
          Effect.provideService(Clock.Clock, this.clock),
        ),
    );
  }

  /** Exercise direct generation with the same persisted AI allowance. */
  async generate() {
    const handlers = await this.handlers;
    return Effect.runPromise(
      handlers
        .generate()
        .pipe(
          Effect.provide(RuntimeContext.phantom),
          Effect.provideService(Clock.Clock, this.clock),
        ),
    );
  }

  /** Let the real Durable Object alarm invoke the production cleanup handler. */
  override async alarm() {
    const handlers = await this.handlers;
    await Effect.runPromise(
      handlers
        .alarm()
        .pipe(
          Effect.provide(RuntimeContext.phantom),
          Effect.provideService(Clock.Clock, this.clock),
        ),
    );
  }
}

export default { fetch: () => new Response("Test worker") };
